"""Subsection 3.4: where the implementation differs from the earlier documents."""

from __future__ import annotations


DEVIATIONS = [
    ['Password recovery',
     'The technical specification and the preliminary design list “recover a password” (function F-1.3) among the functions of the account.',
     'Not implemented. The server enables only the registration feature of Fortify, and the client has no screen for it.',
     'A planned addition (a reset link needs a mail transport); until then the function F-1.3 is not provided.'],
    ['Number of tabs',
     'The product plan (`docs/mvp-plan.md`) describes four tabs of the tab bar.',
     'The tab bar has five tabs: Reading, Library, Quotes, Statistics, Community.',
     'The plan is outdated; the interface is described by Section 12.'],
    ['Generation of the API types',
     'The preliminary design (Table “Programming languages and tools”) names the generation of the types of the client from the OpenAPI contract.',
     'The contract is generated by the server (Scramble), but the types of the client in `src/types/api.ts` are written by hand.',
     'The types are checked by the compiler and by the tests of the client, not by generation.'],
    ['Streak',
     'The specification of the process 4.0 returns the current streak.',
     '`ReadingStatistics::streak` returns the current streak, the longest streak and the mark that the reader has read today.',
     'The refined algorithm (Section 7.4) describes the real result.'],
    ['Import of an EPUB book',
     'The specification of the process 6.0 reads all the chapters and then opens a transaction.',
     'The chapters are read one at a time inside the transaction, and there are more limits (the size of a text, the quota of a reader, the lock of the import).',
     'The memory does not grow with the size of the book; the algorithm of Section 7.5 describes the real order.'],
    ['Hiding of a comment',
     'The specification of the process 8.0 sets the mark of hiding on the content.',
     '`ModerateContent::hide` also lowers the counter of comments of the post when the hidden content is a comment, and it works under the lock of the row.',
     'The counter of comments shows what a reader can see; see Section 7.10.'],
    ['Codes of the errors of the reader',
     'The preliminary design lists a short set of `reader.*` codes.',
     'The code has more: `text_too_large`, `quota_exceeded`, `busy`, `no_text`, `anchor_out_of_range`, `anchor_mismatch`, `chapter_out_of_range`.',
     'The full list is in Section 4.'],
    ['Unit of the offsets of a quote',
     'The preliminary design speaks about the offsets in characters.',
     'The offsets are counted in UTF-16 code units, the unit of a JavaScript string index.',
     'The browser and the server count the same, also for text with emoji.'],
    ['Removing a book by hand',
     'The technical specification (function F-2.7) says that posts already published stay when a reader removes a book.',
     'A book that a reader added by hand is deleted from the catalog together with the last library entry that refers to it, and the posts about it (they refer to the catalog book) are deleted with it by the cascade of the database.',
     'The posts of a book added by hand disappear with the book. This differs from F-2.7 and is to be decided: change the rule or the text of the function.'],
    ['Role of a moderator',
     'The preliminary design says that the role is given by the flag `is_admin` of the account.',
     'The flag exists in the table `users`, but no code reads it: the moderation commands run for whoever can run commands on the server.',
     'In fact the role is the access to the server; the flag is not used.'],
    ['Length of the fields',
     'The technical specification limits a name to 100 characters and a quote to 5000 characters (the preliminary design repeats the 5000).',
     'The form requests accept a name of up to 255 characters and a quote of up to 2000 characters.',
     'The limits of the code are given in Section 5.'],
    ['Library list',
     'The technical specification lists the books of a reader by status.',
     'The list of the library is not divided into pages: the client receives all entries.',
     'Enough for a personal library; a pagination is needed for thousands of books.'],
    ['Stores used by the progress update',
     'Table 11 of the preliminary design shows that the process 3.0 uses the stores D3 and D4.',
     '`RecordReadingLog::handle` also reads the time zone of the reader from the table `users` (the store D1).',
     'The use of D1 by the process 3.0 is to be added to that table.'],
]


def write(d, ctx) -> None:
    d.h2('3.4 Differences between the implementation and the earlier documents')
    d.p('The technical design was written from the code of the finished application. In a few places the code differs '
        'from what the technical specification, the preliminary design or the product plan say. They are listed in '
        + ctx.ref('tab:deviations') + ' so that the documents can be brought in line with the program.')
    ctx.table(d, 'tab:deviations', 'Differences between the implementation and the earlier documents')
    d.table(['Subject', 'Earlier document', 'Implementation', 'Consequence'], DEVIATIONS, [2.0, 3.6, 4.4, 3.2], size=20)
